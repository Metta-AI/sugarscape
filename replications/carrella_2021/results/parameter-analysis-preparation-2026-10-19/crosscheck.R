args <- commandArgs(trailingOnly=TRUE)
stopifnot(length(args)==2, !dir.exists(args[2]))
paths <- read.csv(file.path(args[1], 'cohort-paths.csv'))
tests <- read.csv(file.path(args[1], 'tests.csv'))
stopifnot(nrow(paths)==10, nrow(tests)==30)
adjusted <- p.adjust(tests$raw_p, method='holm')
stopifnot(max(abs(adjusted-tests$holm_adjusted_p)) < 1e-12)
metrics <- c('last_population','minimum_population','price_at475','last_price','maximum_price','mean_price')
continuous <- list(); rare <- list()
for (i in seq_len(nrow(paths))) {
  d <- read.csv(paths$runs[i])
  stopifnot(nrow(d)==128, all(table(d$variant)==64))
  a <- d[d$variant=='native',]; b <- d[d$variant=='independent',]
  continuous[[i]] <- data.frame(original_row=paths$original_row[i], metric=metrics, difference=sapply(metrics,function(m) { points <- sort(unique(c(a[[m]],b[[m]]))); max(abs(ecdf(a[[m]])(points)-ecdf(b[[m]])(points))) }))
  events <- cbind(persistent_late_price=d$price_at475>=10 & d$last_price>=10,low_final_population=d$last_population<50)
  rare[[i]] <- do.call(rbind,lapply(seq_len(ncol(events)),function(j) { v <- events[,j]; x <- sum(v[d$variant=='native']); y <- sum(v[d$variant=='independent']); data.frame(original_row=paths$original_row[i],test=colnames(events)[j],native=x,independent=y,p=fisher.test(matrix(c(x,64-x,y,64-y),nrow=2,byrow=TRUE))$p.value) }))
}
r <- do.call(rbind,rare)
joined <- merge(r,tests,by=c('original_row','test'))
stopifnot(nrow(joined)==20, max(abs(joined$p-joined$raw_p)) < 1e-12)
dir.create(args[2])
write.csv(do.call(rbind,continuous),file.path(args[2],'ecdf.csv'),row.names=FALSE)
write.csv(r,file.path(args[2],'rare-events.csv'),row.names=FALSE)
write.csv(data.frame(tests, r_holm=adjusted),file.path(args[2],'holm.csv'),row.names=FALSE)
