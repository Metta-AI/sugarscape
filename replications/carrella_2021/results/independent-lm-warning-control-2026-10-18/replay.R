options(warn = 1)
args <- commandArgs(trailingOnly = TRUE)
RNGkind("Mersenne-Twister", "Inversion", "Rejection")
set.seed(0)
source(file.path(args[[1]], "setup.R"))
x <- readRDS(args[[2]])
parameters <- c("initial.population", "pmut", "maximum.sugar.endowment", "maximum.spice.endowment", "wealth.reproduction")
predictors <- setdiff(names(x$training), parameters)
stopifnot(length(predictors) == 146L, BOOTSTRAP_N == 200)
result <- linear_regression_fit(x$training, x$testing, parameters, predictors, degree = 1)
saveRDS(result, file.path(args[[3]], "result.rds"))
checks <- list(result_identical = identical(result, x$result), random_state_identical = identical(.Random.seed, x$random_state), bootstrap_fits_per_target = BOOTSTRAP_N)
jsonlite::write_json(checks, file.path(args[[3]], "comparison.json"), auto_unbox = TRUE, pretty = TRUE)
stopifnot(checks$result_identical, checks$random_state_identical)
