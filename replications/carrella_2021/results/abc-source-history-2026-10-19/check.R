library(abc)
library(jsonlite)
args <- commandArgs(trailingOnly=TRUE)
r <- args[[1]]
old <- new.env(parent=asNamespace('abc'))
new <- new.env(parent=asNamespace('abc'))
sys.source(file.path(r,'abc-2.1.R'),envir=old)
sys.source(file.path(r,'abc-2.2.2.R'),envir=new)
stopifnot(identical(formals(old$abc),formals(new$abc)),identical(body(old$abc),body(new$abc)))
stopifnot(identical(formals(abc::abc),formals(new$abc)),identical(body(abc::abc),body(new$abc)))
stopifnot(identical(formals(old$summary.abc),formals(new$summary.abc)),identical(formals(old$summary.abc)$unadj,FALSE))
stopifnot(identical(formals(getS3method('summary','abc')),formals(new$summary.abc)),identical(body(getS3method('summary','abc')),body(new$summary.abc)))
objects <- ls(old)
stopifnot(identical(objects,ls(new)))
changed <- objects[!vapply(objects,function(n) identical(body(get(n,old)),body(get(n,new))) && identical(formals(get(n,old)),formals(get(n,new))),logical(1))]
print(changed)
stopifnot(identical(changed,'hist.abc'))
stopifnot(identical(body(old$summary.abc),body(new$summary.abc)))
write_json(list(old_version='2.1',new_version='2.2.2',installed_version=as.character(packageVersion('abc')),r_version=as.character(getRversion()),objects_in_abc_file=objects,changed_functions=changed,abc_body_and_formals_identical=TRUE,installed_abc_and_summary_match_current_source=TRUE,summary_default_unadj=FALSE,scope='Function source comparison only; not historical runtime equivalence or numerical estimator replay.'),file.path(r,'function-comparison.json'),pretty=TRUE,auto_unbox=TRUE)
print(changed)
