args <- commandArgs(trailingOnly=TRUE)
r <- args[[1]]
d <- read.csv(file.path(r,'bands.csv'))
pdf(file.path(r,'ec-vision-band.pdf'),width=9,height=5)
par(mar=c(5.5,4.3,3.8,1))
plot(d$tick,d$mean,type='n',xlab='Simulation tick',ylab='EC mean vision',ylim=range(d$lower,d$upper,d$paper_lower,d$paper_upper),main='Rule M versus EC: vision uncertainty',sub='Exploratory whole-run bootstrap; overlap does not establish equivalence')
polygon(c(d$tick,rev(d$tick)),c(d$lower,rev(d$upper)),col='#BBD9F1',border=NA)
polygon(c(d$tick,rev(d$tick)),c(d$paper_lower,rev(d$paper_upper)),col='#88888877',border=NA)
lines(d$tick,d$mean,col='#1565A9',lwd=1.7)
legend('topright',legend=c('50-run mean','Approximate simultaneous 95% band','Paper raster interval'),col=c('#1565A9','#BBD9F1','#888888'),lwd=c(2,8,8),bty='n',cex=.9)
dev.off()
